                    db_update('company_settings', ['company_name' => $v['company'], 'email' => $v['email'], 'updated_at' => date('Y-m-d H:i:s')], 'id = 1');
                }
                $done = true;
            } catch (Throwable $e) {
                $errors[] = 'Setup failed: ' . $e->getMessage();
            }
        }
    }
}
