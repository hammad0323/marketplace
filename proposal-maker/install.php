            . "define('APP_KEY', " . var_export(bin2hex(random_bytes(24)), true) . ");\n\n"
            . "// Public proposal links use /proposal/view/{token} (needs mod_rewrite). Set false to use view.php?token=\n"
            . "define('PRETTY_URLS', true);\n\n"
            . "define('APP_TIMEZONE', " . var_export(date_default_timezone_get(), true) . ");\n"
            . "define('APP_DEBUG', false);\n";
        if (@file_put_contents(__DIR__ . '/config.php', $cfg) === false) {
            $errors[] = 'Could not write config.php. Create it manually from config.sample.php.';
        } else {
            if (!defined('DB_HOST')) require __DIR__ . '/config.php';
            try {
